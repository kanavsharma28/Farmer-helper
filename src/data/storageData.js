// Calculation helper for storage quotation
export function calculateStorageQuote({ ratePerQtl, quantity, unit, inwardDate, outwardDate, pickupRequired }) {
  const qtyInQtl = unit === 'mt' ? Number(quantity) * 10 : Number(quantity || 0);

  // Calculate duration in months (minimum 1 month)
  let months = 1;
  if (inwardDate && outwardDate) {
    const inD = new Date(inwardDate);
    const outD = new Date(outwardDate);
    const diffTime = Math.max(0, outD - inD);
    const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
    months = Math.max(1, Math.ceil(diffDays / 30));
  }

  const baseRateTotal = Math.round(ratePerQtl * qtyInQtl * months);
  const insuranceHandling = Math.round(baseRateTotal * 0.04); // 4% WDRA govt insurance & handling
  const pickupTransit = pickupRequired ? Math.round(qtyInQtl * 12) : 0; // ₹12/qtl transit
  const grandTotal = baseRateTotal + insuranceHandling + pickupTransit;

  return {
    qtyInQtl,
    months,
    baseRateTotal,
    insuranceHandling,
    pickupTransit,
    grandTotal,
  };
}
